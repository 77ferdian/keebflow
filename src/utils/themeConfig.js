// Peta fallback untuk kompatibilitas id lama ('slate' -> 'nord', 'emerald' -> 'matrix', dst)
const THEME_ALIASES = {
  slate: 'nord',
  emerald: 'matrix',
  amber: 'tokyo'
};

export function getTheme(themeId) {
  const resolvedId = THEME_ALIASES[themeId] || themeId;
  const found = THEMES.find((t) => t.id === resolvedId);
  return found || THEMES[0];
}
